from pathlib import Path
import scanpy as sc
import pandas as pd

# Define paths
data_file = Path("data/pbmc3k_clustered.h5ad")
results_folder = Path("results")
report_file = results_folder / "InsightCell_Analysis_Report.txt"

results_folder.mkdir(exist_ok=True)

# Check that clustering has completed
if not data_file.exists():
    raise FileNotFoundError(
        "Clustered dataset not found. Complete cell_clustering.py first."
    )

# Load clustered dataset
adata = sc.read_h5ad(data_file)

# Prepare report
lines = []

lines.append("=" * 60)
lines.append("INSIGHTCELL: SINGLE-CELL RNA-SEQ ANALYSIS REPORT")
lines.append("=" * 60)

lines.append("\n1. DATASET SUMMARY")
lines.append(f"Number of cells: {adata.n_obs}")
lines.append(f"Number of genes: {adata.n_vars}")

lines.append("\n2. CLUSTERING SUMMARY")

if "leiden" in adata.obs.columns:
    cluster_counts = adata.obs["leiden"].value_counts().sort_index()

    lines.append(f"Number of clusters: {len(cluster_counts)}")

    for cluster, count in cluster_counts.items():
        lines.append(f"Cluster {cluster}: {count} cells")
else:
    lines.append("Leiden cluster assignments were not found.")

lines.append("\n3. MARKER GENE RESULTS")

marker_file = results_folder / "cluster_marker_genes.csv"

if marker_file.exists():
    markers = pd.read_csv(marker_file)

    lines.append(f"Marker-gene result rows: {len(markers)}")

    for cluster in markers["group"].unique():
        cluster_markers = markers[markers["group"] == cluster]

        if "pvals_adj" in cluster_markers.columns:
            cluster_markers = cluster_markers.sort_values("pvals_adj")

        top_genes = cluster_markers["names"].head(5).tolist()

        lines.append(
            f"Cluster {cluster} candidate markers: {', '.join(top_genes)}"
        )
else:
    lines.append("Marker-gene results were not found.")

lines.append("\n4. OUTPUT FILES")

output_files = [
    "data/pbmc3k_raw.h5ad",
    "data/pbmc3k_filtered.h5ad",
    "data/pbmc3k_normalized.h5ad",
    "data/pbmc3k_pca_umap.h5ad",
    "data/pbmc3k_clustered.h5ad",
    "results/cluster_marker_genes.csv",
    "results/plots/cell_clusters_umap.png",
]

for filename in output_files:
    status = "Available" if Path(filename).exists() else "Not found"
    lines.append(f"{filename}: {status}")

lines.append("\n5. INTERPRETATION")
lines.append(
    "Clusters represent groups of cells with similar expression profiles. "
    "Biological cell-type assignments require marker-gene review."
)

lines.append("\nReport generated by InsightCell.")

# Save report
report_file.write_text("\n".join(lines), encoding="utf-8")

print("\n".join(lines))
print(f"\nReport saved to: {report_file.resolve()}")